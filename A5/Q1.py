import numpy as np

# Create a 1D NumPy array with 5 elements
arr = np.array([10, 20, 30, 40, 50])
print("Original Array:", arr)

# a) Addition of 2 to all elements
add_result = arr + 2
print(add_result)

# b) Multiply 3 with all elements
mul_result = arr * 3
print( mul_result)

# c) Divide every element by 2
div_result = arr / 2
print( div_result)